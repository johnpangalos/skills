#!/usr/bin/env node
// Installs feature-flow-lite for OpenAI Codex CLI, at user level:
//   ~/.agents/skills/feature-flow-lite/   SKILL.md, templates/, agents/ (the role prompts)
//   ~/.agents/skills/ff-usage/            prints per-role tokens and time
//   ~/.codex/agents/ff_<role>.toml        the four roles, generated from agents/<role>.md
//   ~/.codex/feature-flow-lite/hooks.mjs  the hooks, registered in ~/.codex/hooks.json
//
//   node install.mjs                 install or update
//   node install.mjs --model <name>  pin the four roles to that model (default: the session's)
//   node install.mjs --uninstall     remove all of the above
//
// CODEX_HOME moves ~/.codex, as it does for Codex itself.

import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const SKILL = resolve(HERE, '..')
const ROLES = ['investigator', 'implementor', 'simplifier', 'reviewer']
const HOOK_EVENTS = [
  ['UserPromptSubmit'],
  ['PreToolUse', 'Agent'], // Codex's Agent matcher also matches spawn_agent
  ['SubagentStart'],
  ['SubagentStop'],
  ['Stop'],
]

// What Claude Code enforces with a tools list, Codex can only ask for.
const CODEX_NOTES = {
  investigator: "Don't edit files or run anything that changes state; read with the shell (rg, sed, cat).",
  implementor: '',
  simplifier: "Don't run anything that changes state besides your edits; the orchestrator re-runs the checks.",
  reviewer: '',
}

// The agent file's frontmatter fields and body.
export function parseAgent(text) {
  const match = text.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/)
  if (!match) throw new Error('agent file has no frontmatter')
  const fields = {}
  for (const line of match[1].split('\n')) {
    const pair = line.match(/^(\w+):\s*(.*)$/)
    if (pair) fields[pair[1]] = pair[2].trim()
  }
  return { fields, body: match[2].trim() }
}

// TOML basic strings take JSON's escapes; multi-line literal strings take the body as is.
const tomlString = value => JSON.stringify(value)
function tomlMultiline(value) {
  if (value.includes("'''")) throw new Error("agent prompt contains ''' and can't be a TOML literal string")
  return `'''\n${value}\n'''`
}

export function agentToml(role, text, model) {
  const { fields, body } = parseAgent(text)
  const instructions = [body, "You can't spawn subagents.", CODEX_NOTES[role]].filter(Boolean).join('\n\n')
  return [
    `# Generated by feature-flow-lite/codex/install.mjs from agents/${role}.md. Re-run it to update.`,
    `name = ${tomlString(`ff_${role}`)}`,
    `description = ${tomlString(fields.description ?? `Feature-flow-lite ${role}.`)}`,
    ...(model ? [`model = ${tomlString(model)}`] : []),
    ...(fields.effort ? [`model_reasoning_effort = ${tomlString(fields.effort)}`] : []),
    `developer_instructions = ${tomlMultiline(instructions)}`,
    '',
  ].join('\n')
}

const isOurs = handler => typeof handler?.command === 'string' && handler.command.includes('feature-flow-lite/hooks.mjs')

// hooks.json with our handlers removed, then (unless removing) added back once.
export function mergeHooks(config, command, remove = false) {
  const hooks = { ...(config.hooks ?? {}) }
  for (const [event, groups] of Object.entries(hooks)) {
    hooks[event] = groups
      .map(group => ({ ...group, hooks: (group.hooks ?? []).filter(handler => !isOurs(handler)) }))
      .filter(group => group.hooks.length > 0)
    if (hooks[event].length === 0) delete hooks[event]
  }
  if (!remove) {
    for (const [event, matcher] of HOOK_EVENTS) {
      const group = { hooks: [{ type: 'command', command, timeout: 10, statusMessage: 'feature-flow-lite' }] }
      hooks[event] = [...(hooks[event] ?? []), matcher ? { matcher, ...group } : group]
    }
  }
  return { ...config, hooks }
}

function main() {
  const args = process.argv.slice(2)
  const remove = args.includes('--uninstall')
  const modelAt = args.indexOf('--model')
  const model = modelAt >= 0 ? args[modelAt + 1] : undefined
  if (modelAt >= 0 && !model) throw new Error('--model needs a model name')

  const codexHome = process.env.CODEX_HOME || join(homedir(), '.codex')
  const skillsDir = join(homedir(), '.agents', 'skills')
  const skillDir = join(skillsDir, 'feature-flow-lite')
  const usageDir = join(skillsDir, 'ff-usage')
  const agentsDir = join(codexHome, 'agents')
  const ownDir = join(codexHome, 'feature-flow-lite')
  const hooksScript = join(ownDir, 'hooks.mjs')
  const hooksJson = join(codexHome, 'hooks.json')
  const command = `node ${JSON.stringify(hooksScript)}`

  const config = existsSync(hooksJson) ? JSON.parse(readFileSync(hooksJson, 'utf8')) : {}

  if (remove) {
    for (const dir of [skillDir, usageDir]) rmSync(dir, { recursive: true, force: true })
    for (const role of ROLES) rmSync(join(agentsDir, `ff_${role}.toml`), { force: true })
    rmSync(hooksScript, { force: true })
    if (existsSync(hooksJson)) writeFileSync(hooksJson, `${JSON.stringify(mergeHooks(config, command, true), null, 2)}\n`)
    console.log('feature-flow-lite: removed. Usage logs are kept in', ownDir)
    return
  }

  rmSync(skillDir, { recursive: true, force: true })
  mkdirSync(skillDir, { recursive: true })
  cpSync(join(SKILL, 'SKILL.md'), join(skillDir, 'SKILL.md'))
  cpSync(join(SKILL, 'templates'), join(skillDir, 'templates'), { recursive: true })
  cpSync(join(SKILL, 'agents'), join(skillDir, 'agents'), { recursive: true })

  mkdirSync(usageDir, { recursive: true })
  const usageSkill = readFileSync(join(HERE, 'ff-usage', 'SKILL.md'), 'utf8').replaceAll('{{HOOKS}}', hooksScript)
  writeFileSync(join(usageDir, 'SKILL.md'), usageSkill)

  mkdirSync(agentsDir, { recursive: true })
  for (const role of ROLES) {
    const text = readFileSync(join(SKILL, 'agents', `${role}.md`), 'utf8')
    writeFileSync(join(agentsDir, `ff_${role}.toml`), agentToml(role, text, model))
  }

  mkdirSync(ownDir, { recursive: true })
  cpSync(join(HERE, 'hooks.mjs'), hooksScript)
  writeFileSync(hooksJson, `${JSON.stringify(mergeHooks(config, command), null, 2)}\n`)

  console.log(
    [
      'feature-flow-lite: installed for Codex.',
      `  skill   ${skillDir}`,
      `  usage   ${usageDir}`,
      `  agents  ${ROLES.map(role => join(agentsDir, `ff_${role}.toml`)).join(', ')}`,
      `  hooks   ${hooksScript} (registered in ${hooksJson})`,
      model ? `  model   ${model} for all four roles` : '  model   the roles use the session\'s model; --model <name> pins a cheaper one',
      '',
      'Next: start codex, run /hooks and trust the feature-flow-lite hooks, then ask for',
      'a change with $feature-flow-lite. $ff-usage prints per-role tokens and time.',
    ].join('\n'),
  )
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main()
